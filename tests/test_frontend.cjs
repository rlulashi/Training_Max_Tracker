function element() {
  const node = {value:'', textContent:'', hidden:false, disabled:false, inert:false,
    listeners:{}, dataset:{}, style:{}, classList:{add(){},remove(){},toggle(){}},
    addEventListener(name,fn){this.listeners[name]=fn;},
    querySelector(selector){this.matches ||= new Map(); if(!this.matches.has(selector))this.matches.set(selector,element());return this.matches.get(selector);},
    setAttribute(key,value){(this.attributes ||= {})[key]=value;},
    append(...items){(this.children ||= []).push(...items);}, focus(){}, reset(){}, click(){},
    showModal(){this.open=true;},close(){this.open=false;},closest(){return this;},prepend(...items){this.children=[...items,...(this.children||[])];}};
  Object.defineProperty(node,'innerHTML',{get(){return this.html||'';},set(value){this.html=value;this.children=[];}});
  return node;
}
function environment() {
  const elements = new Map();
  const get = key => {if (!elements.has(key)) {const node=element();if(key==='#rowTemplate')node.content={cloneNode:()=>element()};elements.set(key,node);} return elements.get(key);};
  const context = vm.createContext({console, crypto, Date, Math, Number, Object, Array, Map, Set, JSON,
    document:{querySelector:get,querySelectorAll:()=>[],getElementById:id=>get('#'+id),createElement:element},
    window:{TrainingStore:{save(){},progress(){}}}, alert:message=>{throw new Error(message);},confirm:()=>true,
    setTimeout,clearTimeout,Blob,URL,location:{reload(){}},localStorage:{getItem(){return null},setItem(){},removeItem(){}}});
  return {context,get,run:code=>vm.runInContext(code,context)};
}

